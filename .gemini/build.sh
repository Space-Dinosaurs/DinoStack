#!/usr/bin/env bash
# Module: .gemini/build.sh
# Role: Build script for the Gemini CLI adapter
# Inputs: content/rules/*.md, content/references/*.md, content/commands/*.md, content/agents/*.md
# Outputs: .gemini/skills/dinostack/SKILL.md (full assembled methodology body,
#          trigger-loaded via Gemini CLI's `activate_skill` - DS-184),
#          .gemini/GEMINI.md (a small always-loaded stub pointing at the skill
#          - no longer carries the methodology body itself, DS-184),
#          .gemini/references/*.md (hardlinks), .gemini/commands/*.toml
#          (generated TOML), .gemini/agents/*.md (generated markdown)
# Side-effects: removes stale generated files from previous builds
# Consumers: .gemini/install.sh, hooks/pre-commit, .github/workflows/adapter-sync.yml,
#            scripts/build-all.sh, content/commands/ds-update-agentic-engineering.md,
#            scripts/check-gemini-skill-budget.sh (measures the SKILL.md and
#            GEMINI.md this script produces)
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONTENT="$REPO_DIR/content"
GEMINI_DIR="$REPO_DIR/.gemini"
REFS_DST="$GEMINI_DIR/references"
COMMANDS_DST="$GEMINI_DIR/commands"
AGENTS_DST="$GEMINI_DIR/agents"
SKILL_DST="$GEMINI_DIR/skills/dinostack"

# ---------------------------------------------------------------------------
# Portable inode helper (macOS uses -f, Linux uses -c)
# ---------------------------------------------------------------------------

get_inode() {
  if stat -c %i /dev/null >/dev/null 2>&1; then
    stat -c %i "$1"
  else
    stat -f %i "$1"
  fi
}

# ---------------------------------------------------------------------------
# Step 1: Generate the dinostack skill (SKILL.md) and the GEMINI.md stub
#
# DS-184: Gemini CLI supports project-local trigger-loaded skills
# (.gemini/skills/<name>/SKILL.md, discovered at session start via
# `activate_skill` - see docs/cli/skills.md on google-gemini/gemini-cli).
# The full assembled methodology body (all content/sections/*.md plus
# content/rules/code-standards.md and content/rules/conventions.md, same
# content this file used to write directly into GEMINI.md) now lives in
# .gemini/skills/dinostack/SKILL.md instead, so it loads on trigger rather
# than unconditionally in every session. GEMINI.md is regenerated as a
# small always-loaded stub that points at the skill.
# ---------------------------------------------------------------------------

GEMINI_MD_DST="$GEMINI_DIR/GEMINI.md"
