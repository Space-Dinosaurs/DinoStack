#!/usr/bin/env python3
"""
Purpose: Guard against a malformed YAML/TOML `description:` scalar anywhere in
         the hand-authored `content/agents/*.md` sources OR the 11-adapter
         generated output. `check-adapter-sync` only diffs regenerated bytes
         against committed bytes - it proves the build is reproducible, never
         that the frontmatter it reproduces is semantically valid. This test
         is the layer that actually parses every frontmatter block with a real
         parser (PyYAML / tomllib) and asserts it decodes.

         Fixed by DS (frontmatter-yaml-validity, 2026-08): four canonical
         agent files (`engineer`, `goal-condition-evaluator`, `qa-engineer`,
         `skeptic`) had an unquoted `description:` scalar containing a bare
         `: ` sequence, which `yaml.safe_load` rejects with `ScannerError`.
         Claude Code's own build path (raw hardlink/cat) tolerated this, so
         the defect shipped invisibly; a stricter downstream consumer (or a
         future unquoted `#` causing SILENT TRUNCATION, not an error) would
         not have been caught by any existing gate.

Public API: pytest test functions. Run with
              python3 -m pytest bin/tests/test_frontmatter_validity.py -q
            (.github/workflows/bin-tests.yml's `python-bin-tests` job runs
            `python3 -m pytest bin/tests/ -q`, auto-discovering; no additional
            CI wiring is required. Reads already-committed adapter output -
            does NOT invoke `bash scripts/build-all.sh` itself; run that
            first locally if you want to test freshly-generated output.)

Upstream deps: content/agents/*.md, and the generated-frontmatter surface
               enumerated in DISCOVERY_SPECS below (11-adapter build output
               plus .github/{agents,prompts}); stdlib + pyyaml (+ tomllib,
               stdlib on Python >=3.11, matching this repo's pinned CI
               interpreter).

Downstream consumers: none (CI gate only).

Scope note - why some adapter files are NOT covered here (documented per
CLAUDE.md's frontmatter-fix obligation, not an oversight):
  - `content/commands/*.md` / `.cursor/commands/*.md`: hand-authored command
    docs open with a bare `# /ds-*` heading and carry NO YAML frontmatter at
    all - Cursor commands are hardlinked from content/commands/ verbatim.
    Nothing to parse; a stray `---` fence appearing here would be a distinct
    defect from this test's scope.
  - Adapter-root docs (`README.md`, `AGENTS.md`, `CLAUDE.md`, `GEMINI.md`,
    `.github/copilot-instructions.md`, `.github/PULL_REQUEST_TEMPLATE.md`):
    plain prose, no frontmatter. `.github/copilot-instructions.md` is a
    DS-186 stub (pointer to the skill below) - the methodology body, and
    the frontmatter, now live at `.github/skills/dinostack/SKILL.md`,
    which IS covered (see the DiscoverySpecs list below).
  - `*/references/*.md`: hardlinked reference docs, no frontmatter.
  - `.github/instructions/*.md`: carries a DIFFERENT frontmatter schema
    (`applyTo:` globs, no `description:` field) - out of scope for this gate.
  - `.kimi/skills/ds-*/SKILL.md`: generated per-command skill bodies built by
    `.kimi/build.sh` from `content/commands/`. `.kimi/skills/*/` is gitignored
    build output (see `.gitignore`, with a `!.kimi/skills/dinostack/`
    carve-out for the root skill) - it does not exist on a pristine checkout,
    so a glob pointed at it would match 0 files in CI and make every
    assertion in this file vacuously true (this is exactly the F3 failure
    mode `test_discovery_globs_are_nonempty` exists to catch). Not covered.
  - `.hermes/README.md`: a plain README, no frontmatter of its own; `.hermes/`'s
    frontmatter surface is `.hermes/SKILL.md`, already covered above.

  Entry/root skill bodies that DO carry real `description:` frontmatter and
  ARE covered (corrected from an earlier version of this note that claimed
  these carried frontmatter only in a hand-authored sidecar or none at all -
  that was wrong; all of the following begin with a `---` block containing a
  genuine `description:` field and parse today):
  `.codex/skills/{dinostack,brief,implement-ticket,wrap}/SKILL.md`
  (generated by `scripts/codex-skills.py`), and the single root
  `skills/dinostack/SKILL.md` under each of `.claude/`, `.opencode/`,
  `.omp/`, `.openclaw/`, `.pi/`, `.github/` (DS-186: the Copilot
  adapter's trigger-loaded skill body, gaining its own `name:`/
  `description:` frontmatter when the methodology body moved out of the
  always-loaded `.github/copilot-instructions.md` stub), and `.gemini/`
  (DS-184: the Gemini adapter's trigger-loaded skill body, generated by
  `.gemini/build.sh`) - that is 11 root/entry skill bodies total, not 9
  (a prior revision of this note omitted `.pi/skills/dinostack/SKILL.md`,
  a tracked, non-gitignored file built by `.pi/build.sh:45-50`, from both
  the covered list and the exclusion list above - it was simply uncovered
  by any DiscoverySpec until that fix). This enumeration was re-derived
  independently (every tracked `.md`/`.mdc` file with a `---` block
  containing a `description:` field, minus every path the DISCOVERY_SPECS
  globs below resolve) and the remainder confirmed empty - do not re-add
  an entry here without re-running that same complement check; asserting
  completeness without doing so is exactly how `.pi/`, `.github/`, and
  `.gemini/` were each missed in turn.

Failure modes this test exists to catch:
  - F1: an unquoted `description:` value containing `: ` - parses to a
    `ScannerError`/`TOMLDecodeError`. Caught by test_all_frontmatter_parses.
  - F2: an unquoted `#` mid-value - parses "successfully" but SILENTLY
    TRUNCATES everything after the `#` (YAML end-of-line comment; TOML has no
    such implicit-comment risk inside a basic string, so this is YAML-only).
    Caught by test_description_nonempty_and_reasonable, which asserts the
    decoded description is non-trivially long (a truncation to an empty or
    near-empty string is the observable symptom).
  - F3: a discovery glob silently matching zero files (a moved/renamed
    directory, typo'd pattern) would make every assertion in this file
    vacuously true. Caught by test_discovery_globs_are_nonempty.
  - F4: a DiscoverySpec glob pointing at gitignored build output, which
    would match 0 files in CI (F3) but could match locally-generated files
    in a dirty working tree - a false-pass local/CI split. Caught by
    test_discovery_specs_point_at_tracked_files, which asserts every
    resolved path is `git ls-files`-tracked (following symlinks through
    adapter directories like `.claude/agents` to their physical target).

Performance: parses ~200 small frontmatter blocks; well under a second.
"""
from __future__ import annotations

import re
import subprocess
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

import pytest
import yaml

_REPO_ROOT = Path(__file__).resolve().parent.parent.parent

_FRONTMATTER_RE = re.compile(r"\A---\n(.*?\n)---\n", re.DOTALL)


@dataclass(frozen=True)
class DiscoverySpec:
    label: str
    glob: str
    kind: str  # "yaml" (--- fenced) or "toml" (whole-file TOML)
    min_count: int


# Every glob below is an ALLOW-list entry: a location known to carry a
# `description:` field in its frontmatter. See the module docstring's
# "Scope note" for the excluded locations and why.
DISCOVERY_SPECS: list[DiscoverySpec] = [
    DiscoverySpec("content/agents (canonical source)", "content/agents/*.md", "yaml", 15),
    DiscoverySpec(".claude/agents", ".claude/agents/*.md", "yaml", 15),
    DiscoverySpec(".claude/commands", ".claude/commands/*.md", "yaml", 20),
    DiscoverySpec(".opencode/agents", ".opencode/agents/*.md", "yaml", 15),
    DiscoverySpec(".opencode/commands", ".opencode/commands/*.md", "yaml", 20),
    DiscoverySpec(".gemini/agents", ".gemini/agents/*.md", "yaml", 15),
    DiscoverySpec(".gemini/commands (toml)", ".gemini/commands/*.toml", "toml", 20),
    DiscoverySpec(".codex/agents (toml)", ".codex/agents/*.toml", "toml", 15),
    DiscoverySpec(".cursor/rules", ".cursor/rules/*.mdc", "yaml", 4),
    DiscoverySpec(".pi/prompts", ".pi/prompts/*.md", "yaml", 20),
    DiscoverySpec(".openclaw/skills (commands)", ".openclaw/skills/ds-*/SKILL.md", "yaml", 20),
    DiscoverySpec(".openclaw/skills (agents)", ".openclaw/skills/agent-*/SKILL.md", "yaml", 15),
    DiscoverySpec(".github/agents (copilot)", ".github/agents/*.md", "yaml", 15),
    DiscoverySpec(".github/prompts (copilot)", ".github/prompts/*.md", "yaml", 20),
    DiscoverySpec(".hermes/SKILL.md", ".hermes/SKILL.md", "yaml", 1),
    DiscoverySpec(".codex/skills (native, generated)", ".codex/skills/*/SKILL.md", "yaml", 4),
    DiscoverySpec(".claude/skills/dinostack", ".claude/skills/dinostack/SKILL.md", "yaml", 1),
    DiscoverySpec(".opencode/skills/dinostack", ".opencode/skills/dinostack/SKILL.md", "yaml", 1),
    DiscoverySpec(".omp/skills/dinostack", ".omp/skills/dinostack/SKILL.md", "yaml", 1),
    DiscoverySpec(".openclaw/skills/dinostack (root)", ".openclaw/skills/dinostack/SKILL.md", "yaml", 1),
    DiscoverySpec(".pi/skills/dinostack", ".pi/skills/dinostack/SKILL.md", "yaml", 1),
    DiscoverySpec(".github/skills/dinostack (copilot, DS-186)", ".github/skills/dinostack/SKILL.md", "yaml", 1),
    DiscoverySpec(".gemini/skills/dinostack", ".gemini/skills/dinostack/SKILL.md", "yaml", 1),
]


def _resolve_spec(spec: DiscoverySpec) -> list[Path]:
    return sorted(_REPO_ROOT.glob(spec.glob))


def _extract_yaml_frontmatter(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    m = _FRONTMATTER_RE.match(text)
    if m is None:
        raise AssertionError(
            f"{path.relative_to(_REPO_ROOT)}: no well-formed '---' frontmatter "
            f"block at byte 0. First 120 chars: {text[:120]!r}"
        )
    return yaml.safe_load(m.group(1)) or {}


def _extract_toml(path: Path) -> dict:
    with open(path, "rb") as f:
        return tomllib.load(f)


def _tracked_files() -> set[str]:
    """`git ls-files`, relative-to-repo-root paths. Used to assert every
    DiscoverySpec glob resolves only to committed files, never gitignored
    build output - the exact defect class that caused the round-1 Critical
    (a spec pointed at `.kimi/skills/*/SKILL.md`, gitignored generated
    output, matching 0 files on a pristine checkout and making every
    downstream assertion vacuously true)."""
    result = subprocess.run(
        ["git", "ls-files"],
        cwd=_REPO_ROOT,
        capture_output=True,
        text=True,
        check=True,
    )
    return set(result.stdout.splitlines())


def test_discovery_specs_point_at_tracked_files():
    """Mechanical guard against the round-1 Critical failure mode
    recurring: a DiscoverySpec glob must resolve only to git-tracked
    (committed) paths. A spec pointed at gitignored build output would match
    0 files on a pristine CI checkout (caught by
    test_discovery_globs_are_nonempty) OR, worse, match locally-generated
    files that happen to exist in a dirty working tree but are absent on a
    fresh clone - silently passing locally while being broken in CI. Asserting
    trackedness directly makes this class of defect self-enforcing instead of
    depending on a manual audit."""
    tracked = _tracked_files()
    real_root = _REPO_ROOT.resolve()
    for spec in DISCOVERY_SPECS:
        for path in _resolve_spec(spec):
            # Resolve through symlinks first (e.g. `.claude/agents` is a
            # symlink to `content/agents`; git tracks the physical target
            # path, not the symlinked one, so comparing the raw glob-matched
            # path against `git ls-files` would false-positive on every file
            # reached through a symlinked adapter directory).
            real_path = path.resolve()
            rel = str(real_path.relative_to(real_root))
            assert rel in tracked, (
                f"{spec.label}: resolved path {path.relative_to(_REPO_ROOT)} "
                f"(physical: {rel!r}) is not tracked by git (not in `git "
                f"ls-files`) - this DiscoverySpec may be pointing at "
                f"gitignored build output, which would silently pass in a "
                f"dirty local working tree while being broken (0 matches) on "
                f"a pristine CI checkout."
            )


def test_discovery_globs_are_nonempty():
    """Catches F3: a glob pointed at a moved/renamed/typo'd directory must
    fail loud, not silently pass every downstream assertion on zero files."""
    for spec in DISCOVERY_SPECS:
        matches = _resolve_spec(spec)
        assert len(matches) >= spec.min_count, (
            f"{spec.label}: glob {spec.glob!r} matched {len(matches)} files, "
            f"expected at least {spec.min_count}. Discovery glob may be stale "
            f"(renamed directory, typo'd pattern) - a near-zero match count "
            f"would make every other assertion in this file vacuously true."
        )


def test_all_frontmatter_parses():
    """Catches F1: an unquoted 'description: ...: ...' breaks the parser
    with a raised error rather than silently misparsing."""
    for spec in DISCOVERY_SPECS:
        for path in _resolve_spec(spec):
            rel = path.relative_to(_REPO_ROOT)
            try:
                if spec.kind == "yaml":
                    _extract_yaml_frontmatter(path)
                else:
                    _extract_toml(path)
            except (yaml.YAMLError, tomllib.TOMLDecodeError) as exc:
                raise AssertionError(
                    f"{rel}: frontmatter failed to parse - likely an "
                    f"unquoted ': ' inside a description value. Error: {exc}"
                ) from exc


def test_description_nonempty_and_reasonable():
    """Catches gross truncation (e.g. a description collapsed to a bare
    "<!--" HTML-comment opening marker - the actual pre-existing bug this
    test suite uncovered and this repo fixed in .opencode/build.sh and
    .gemini/build.sh). This is a coarse length heuristic; the byte-for-byte
    mechanism for F2 (mid-value truncation at an unquoted '#') is asserted
    precisely by test_no_unquoted_hash_in_plain_scalar_description below."""
    for spec in DISCOVERY_SPECS:
        for path in _resolve_spec(spec):
            rel = path.relative_to(_REPO_ROOT)
            parsed = (
                _extract_yaml_frontmatter(path)
                if spec.kind == "yaml"
                else _extract_toml(path)
            )
            desc = parsed.get("description")
            assert desc, f"{rel}: frontmatter has no non-empty 'description' key"
            # Threshold picked below the shortest legitimate observed value
            # (8 chars, e.g. "/ds-cost").
            assert len(desc.strip()) >= 6, (
                f"{rel}: description is suspiciously short ({desc!r}) - "
                f"possible silent truncation at an unquoted '#' comment marker"
            )


_RAW_DESC_LINE_RE = re.compile(r'^description:[ \t]*(.*)$', re.MULTILINE)


_NEW_KEY_RE = re.compile(r'^\S[^:]*:')


def _plain_scalar_continuation_lines(fm_text: str, first_line_end: int) -> list[str]:
    """A YAML plain (unquoted) scalar may fold onto subsequent lines as long
    as each continuation line is indented and does not itself start a new
    top-level `key:` mapping entry. Collect those continuation lines so the
    ' #' comment-marker check below covers them too, not just the first
    physical line - a description that wraps and hides the '#' on line 2+
    would otherwise slip past undetected."""
    rest = fm_text[first_line_end:].split("\n")
    continuation: list[str] = []
    for line in rest:
        if not line.strip():
            break  # blank line ends the scalar
        if not line[0].isspace():
            break  # unindented - not a continuation, likely the next key
        if _NEW_KEY_RE.match(line.strip()):
            break  # an indented "key:" line is a nested mapping, not a continuation
        continuation.append(line)
    return continuation


def _assert_no_unquoted_hash_in_description(path: Path, rel_label: str | None = None) -> None:
    """Core single-file check, factored out of
    test_no_unquoted_hash_in_plain_scalar_description so the regression test
    below can exercise this exact production code path (including the
    `raw_line_match.end() + 1` arithmetic) against a synthetic fixture,
    rather than duplicating the formula in a separate assertion that would
    not actually catch a regression at the call site."""
    rel = rel_label if rel_label is not None else path.relative_to(_REPO_ROOT)
    text = path.read_text(encoding="utf-8")
    m = _FRONTMATTER_RE.match(text)
    assert m is not None, f"{rel}: frontmatter block missing"
    fm_text = m.group(1)
    raw_line_match = _RAW_DESC_LINE_RE.search(fm_text)
    if raw_line_match is None:
        return  # no single-line 'description:' key (unexpected, but not this test's concern)
    raw_value = raw_line_match.group(1)
    is_quoted_or_block = raw_value.startswith(('"', "'", ">", "|"))
    if is_quoted_or_block:
        return
    assert " #" not in raw_value, (
        f"{rel}: raw description line contains an unquoted ' #' - "
        f"this is a YAML comment marker that SILENTLY TRUNCATES the "
        f"scalar at parse time. Quote the description value."
    )
    for cont_line in _plain_scalar_continuation_lines(fm_text, raw_line_match.end() + 1):
        assert " #" not in cont_line, (
            f"{rel}: a folded continuation line of the plain-scalar "
            f"'description:' value contains an unquoted ' #' - this "
            f"is a YAML comment marker that SILENTLY TRUNCATES the "
            f"scalar at parse time. Quote the description value."
        )


def test_no_unquoted_hash_in_plain_scalar_description():
    """Precisely catches F2: an unquoted mid-value '#' truncates a YAML
    plain scalar at parse time WITHOUT raising and WITHOUT necessarily
    producing a short result (e.g. "General purpose agent # internal note"
    parses "successfully" to the 22-char string "General purpose agent" -
    long enough to slip past the length heuristic above but still silently
    dropping everything from the '#' onward). This test instead inspects the
    RAW (unparsed) description line(s): if it is a plain (unquoted, unfolded)
    scalar, a ' #' substring anywhere in it - including on a folded
    continuation line - is unconditionally a YAML comment start - "quote the
    description or don't use a hash" is the fix, never "the hash is fine
    here"."""
    for spec in DISCOVERY_SPECS:
        if spec.kind != "yaml":
            continue  # TOML basic strings have no implicit '#' comment risk
        for path in _resolve_spec(spec):
            _assert_no_unquoted_hash_in_description(path)


def test_plain_scalar_continuation_lines_finds_folded_hash(tmp_path):
    """Regression test for an off-by-one in the production call site
    (`_assert_no_unquoted_hash_in_description`'s call to
    `_plain_scalar_continuation_lines`): `_RAW_DESC_LINE_RE` uses `$` under
    `re.MULTILINE`, so `raw_line_match.end()` lands ON the newline that ends
    the first physical line, not past it. Calling the helper with that raw
    `.end()` fed it a slice beginning with `"\\n"`, whose first
    `.split("\\n")` element is the empty string `''`; `if not line.strip():
    break` then fired immediately and the function returned `[]` for every
    input, silently disabling the folded-continuation-line coverage that
    `test_no_unquoted_hash_in_plain_scalar_description` depends on.

    This test goes through the ACTUAL production function
    (`_assert_no_unquoted_hash_in_description`) against a synthetic fixture
    file matching the proven-live mutation example (a plain scalar
    description folding onto a second line that hides an unquoted '#'), so a
    revert of the `+ 1` at the call site is caught here - a test that merely
    re-typed the corrected arithmetic in its own assertion would not depend
    on the production code being correct and would not catch that regression."""
    fixture = tmp_path / "fixture.md"
    fixture.write_text(
        "---\n"
        "name: foo\n"
        "description: Plans architecture and design work\n"
        "  and continues onto a second line # hidden truncation here\n"
        "model: sonnet\n"
        "---\n"
        "body\n",
        encoding="utf-8",
    )
    with pytest.raises(AssertionError, match="folded continuation line"):
        _assert_no_unquoted_hash_in_description(fixture, rel_label="fixture.md")


if __name__ == "__main__":
    sys.exit(pytest.main([__file__, "-v"]))
