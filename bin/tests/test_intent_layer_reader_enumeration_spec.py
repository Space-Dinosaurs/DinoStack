#!/usr/bin/env python3
"""
Spec test for the intent-layer reader enumeration ("Architect / Investigator /
Engineer read docs/overview/{vision,requirements}.md").

The Engineer was added as a reader of the operator-owned product-intent layer
alongside Architect and Investigator. That enumeration is restated in prose
across seven canonical sites, and a first pass at adding Engineer updated
only three of them - the omission was caught only by a manual Skeptic review,
not by any gate. This test sweeps all seven canonical sites (adapter copies
are regenerated by scripts/build-all.sh and are out of scope here) and fails
if any of them still names only Architect and Investigator as readers.

Precedent: _ENFORCER_SUBCOUNT_SITES in test_tracker_writeback_ranking_spec.py.
"""

from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent.parent

# Each entry: (path, substring that must be present once Engineer is included
# as a reader of the intent layer at that site).
_INTENT_LAYER_READER_SITES = [
    (
        REPO_ROOT / "content" / "sections" / "04-risk-classification.md",
        "the Engineer reads them before implementing",
    ),
    (
        REPO_ROOT / "content" / "references" / "planning-artifacts.md",
        "the Engineer reads them before implementing",
    ),
    (
        REPO_ROOT / "content" / "references" / "conventions-detail.md",
        "Architect, Investigator, and Engineer read them",
    ),
    (
        REPO_ROOT / "README.md",
        "Architect, Investigator, and Engineer read them",
    ),
    (
        REPO_ROOT / "content" / "commands" / "ds-init-project.md",
        "Architect and Investigator read them when present, and Engineer reads them",
    ),
    (
        REPO_ROOT / "content" / "commands" / "ds-init-project.md",
        "Engineer reads them before implementing",
    ),
    (
        REPO_ROOT / "docs" / "components.md",
        "Architect, Investigator, and Engineer read them",
    ),
]


def test_intent_layer_reader_enumeration_includes_engineer_everywhere():
    missing = []
    for path, expected in _INTENT_LAYER_READER_SITES:
        if not path.exists():
            missing.append(f"{path}: file does not exist")
            continue
        text = path.read_text(encoding="utf-8")
        if expected not in text:
            missing.append(
                f"{path.relative_to(REPO_ROOT)} missing expected Engineer-"
                f"inclusive reader phrasing: {expected!r}"
            )
    assert not missing, "\n".join(missing)


def test_ds_init_project_has_both_intent_layer_sites():
    # ds-init-project.md carries two distinct sites (the operator-owned-files
    # note, and the numbered post-scaffold checklist item). Both must be
    # present and both must be Engineer-inclusive - a single combined
    # assertion above could pass on either site alone.
    path = REPO_ROOT / "content" / "commands" / "ds-init-project.md"
    text = path.read_text(encoding="utf-8")
    sites = [
        s for p, s in _INTENT_LAYER_READER_SITES if p == path
    ]
    assert len(sites) == 2, "expected exactly 2 ds-init-project.md sites in the sweep list"
    for expected in sites:
        assert expected in text, (
            f"ds-init-project.md missing site: {expected!r}"
        )


if __name__ == "__main__":
    raise SystemExit(pytest.main([__file__, "-v"]))
